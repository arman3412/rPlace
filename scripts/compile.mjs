import solc from 'solc';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
const sources = Object.fromEntries(
  await Promise.all(
    ['PixelChain', 'Benchmarks'].map(async (n) => [
      `${n}.sol`,
      { content: await readFile(`contracts/${n}.sol`, 'utf8') },
    ]),
  ),
);
const input = {
  language: 'Solidity',
  sources,
  settings: {
    optimizer: { enabled: true, runs: 200 },
    evmVersion: 'shanghai',
    outputSelection: {
      '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object', 'storageLayout'] },
    },
  },
};
const output = JSON.parse(solc.compile(JSON.stringify(input)));
for (const error of output.errors ?? []) {
  if (error.severity === 'error') throw new Error(error.formattedMessage);
  console.warn(error.formattedMessage);
}
await mkdir('artifacts', { recursive: true });
for (const file of Object.values(output.contracts))
  for (const [name, contract] of Object.entries(file))
    await writeFile(`artifacts/${name}.json`, JSON.stringify(contract, null, 2));
await writeFile(
  'src/lib/abi.ts',
  `// Generated by npm run compile.\nexport const abi = ${JSON.stringify(output.contracts['PixelChain.sol'].PixelChain.abi, null, 2)} as const;\n`,
);
console.log(`Compiled with solc ${solc.version()}, optimizer 200, EVM Shanghai`);
